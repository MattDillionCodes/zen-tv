package com.zen.tv

import android.content.Context
import android.graphics.BitmapFactory
import androidx.compose.ui.graphics.ImageBitmap
import androidx.compose.ui.graphics.asImageBitmap
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import java.io.File
import java.io.InputStream

/** A wallpaper Zen can show: one of the presets shipped in assets, or a photo uploaded from a phone. */
sealed interface ZenWallpaper {
    /** What [ZenPrefs.wallpaper] stores. Uploads use the bare file name so older settings keep working. */
    val id: String

    data class Builtin(val name: String, val label: String) : ZenWallpaper {
        override val id: String get() = "builtin:$name"
    }

    data class Uploaded(val file: File) : ZenWallpaper {
        override val id: String get() = file.name
    }
}

object WallpaperLibrary {
    /** Generated by tools/Wallpapers.java; files live in assets/wallpapers/<name>.jpg. */
    val builtins = listOf(
        ZenWallpaper.Builtin("01-enso", "Ensō"),
        ZenWallpaper.Builtin("02-mist", "Mist"),
        ZenWallpaper.Builtin("03-dunes", "Dunes"),
        ZenWallpaper.Builtin("04-ripples", "Ripples"),
        ZenWallpaper.Builtin("05-stone-garden", "Stone garden"),
        ZenWallpaper.Builtin("06-still-sea", "Still sea"),
    )

    /** Presets first, then uploads oldest to newest — the order the Wallpaper setting cycles through. */
    fun all(context: Context): List<ZenWallpaper> = builtins + uploads(context)

    private fun uploads(context: Context): List<ZenWallpaper.Uploaded> =
        UploadServer.wallpaperDir(context)
            .listFiles { f -> f.name.endsWith(".jpg") }
            .orEmpty()
            .sortedBy { it.name }
            .map { ZenWallpaper.Uploaded(it) }

    suspend fun load(context: Context, wallpaper: ZenWallpaper): ImageBitmap? = withContext(Dispatchers.IO) {
        val open: () -> InputStream = when (wallpaper) {
            is ZenWallpaper.Builtin -> { { context.assets.open("wallpapers/${wallpaper.name}.jpg") } }
            is ZenWallpaper.Uploaded -> { { wallpaper.file.inputStream() } }
        }
        runCatching {
            val bounds = BitmapFactory.Options().apply { inJustDecodeBounds = true }
            open().use { BitmapFactory.decodeStream(it, null, bounds) }
            var sample = 1
            // Sample by both sides: a very tall photo must not decode at full size.
            while (bounds.outWidth / (sample * 2) >= 1920 || bounds.outHeight / (sample * 2) >= 1080) sample *= 2
            open().use { BitmapFactory.decodeStream(it, null, BitmapFactory.Options().apply { inSampleSize = sample }) }
                ?.asImageBitmap()
        }.getOrNull()
    }
}
